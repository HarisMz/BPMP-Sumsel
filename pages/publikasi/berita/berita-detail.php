                    <p>Jakarta, Kemendikdasmen --- Kementerian Pendidikan Dasar dan Menengah (Kemendikdasmen), menekankan pentingnya partisipasi semua pihak dalam mewujudkan Pendidikan Bermutu untuk Semua.</p>
                    <p>Partisipasi tersebut diwujudkan dalam bentuk kerja sama program prioritas Kemendikdasmen, antara lain penguatan pendidikan karakter, revitalisasi Usaha Kesehatan Sekolah (UKS), revitalisasi satuan pendidikan, termasuk dalam peningkatan implementasi pembelajaran mendalam (PM), koding dan kecerdasan artifisial (KA).</p>
                    <p>Sebagai wujud partisipasi semesta, pada bulan Juni 2025 lalu, Kemendikdasmen telah menggandeng berbagai mitra kerjasama seperti Lembaga Pendidikan Ma’arif Nahdlatul Ulama, Pimpinan Pusat Himpunan Sekolah dan Madrasah - Islam Nusantara, Majelis Dikdasmen dan PNF, Pimpinan Pusat Muhammadiyah, Majelis Pendidikan Kristen Indonesia (MPKI), Majelis Nasional Pendidikan Katolik (MNPK), INOVASI, Perkumpulan Ruang Belajar Aqil, Kelompok Kompas Gramedia, The SMERU Research Institute, UNESCO, UNICEF, Universitas Atma Jaya Yogyakarta, Universitas Negeri Malang, dan Perguruan Tinggi serta yayasan kelembagaan pendidikan lainnya.</p>
                    <p>Dalam rangka percepatan implementasi, semua organisasi pendidikan tersebut bersepakat untuk bersinergi dan berkolaborasi dalam menyelaraskan program pendidikan.</p>
                    <p>Tindak lanjut dari kerja sama tersebut salah satunya adalah pelaksanaan bimbingan teknis penguatan pendidikan karakter, PM, koding dan KA. Di semester kedua ini kerja sama tersebut sudah mulai dilaksanakan dengan mitra kerja sama untuk beberapa sekolah-sekolah sasaran secara bertahap.</p>
                    <p>Secara berkala semua mitra yang berkomitmen dan telah menyusun rencana tindak lanjut akan difasilitasi oleh Kemendikdasmen.</p>
                    <p>Ruang lingkup kerjasama tersebut bukan hanya sebatas PM, KA/ koding, namun juga program penguatan karakter melalui 7 Kebiasaan Anak Indonesia Hebat, Revitalisasi Sekolah, Digitalisasi Pembelajaran, Penguatan UKS, dan sebagainya.</p>
                    <p>Komitmen ini merupakan wujud nyata semangat gotong royong mewujudkan Pendidikan Bermutu untuk Semua.</p>
                    <p>Bimbingan Teknis seperti di Jawa Tengah merupakan tindak lanjut dari kesepakatan kerja sama di atas. Kesiapan sekolah sasaran dan usulan tindak lanjut yang telah diajukan Majelis Dikdasmen PP Muhammadiyah menjadi dasar implementasi Bimbingan Teknis tersebut.</p>
                    <p>Adapun rencana kerjasama bimbingan teknis dengan mitra penyelenggara pendidikan lainnya akan segera dilaksanakan secara bertahap, termasuk tentunya sekolah negeri dengan berbagai skema pendanaan termasuk melalui Bantuan Operasional Sekolah (BOS) Kinerja.</p>
                    <p>Direktur Jenderal Pendidikan Anak Usia Dini, Pendidikan Dasar, dan Pendidikan Menengah, Gogot Suharwoto dalam rilisnya, menyampaikan bahwa Ditjen PAUD Dasmen telah menjalin kerjasama dengan sejumlah mitra pendidikan.</p>
                    <p>Semua organisasi pendidikan yang memiliki program yang sejalan dengan program prioritas Ditjen Paudasmen sudah diundang untuk melakukan penyelarasan program.</p>
                    <p>“Mitra yang telah diundang diberikan kesempatan untuk mengusulkan program Rencana Tindak Lanjut (RTL) yang sesuai dengan program prioritas Kemendikdasmen. Usulan tersebut akan tindaklanjuti berbasis kesiapan mitra dan usulan yang sudah masuk. Selanjutnya, Ditjen PAUD Dasmen akan melakukan rapat koordinasi guna memastikan semua mitra mendapatkan kesempatan yang sama, yang belum memperoleh undangan pada kegiatan bimtek pada bulan ini akan difasilitasi pada kegiatan bimbingan teknis berikutnya,” ujar Dirjen Gogot.</p>
                    <p>Lebih lanjut, program PM, KA/Koding ini merupakan program yang berkelanjutan yang ditargetkan kepada 45 ribu sekolah di seluruh Indonesia yang merupakan penerima BOS Kinerja dan BOS regular dengan jumlah siswa besar. Program tersebut tidak hanya berhenti di tahun ini, namun di tahun 2025 merupakan awal mula penerapan PM, KA/koding.</p>
                    <p>Pada Agustus 2025, Kemendikdasmen melalui Ditjen PAUD Dasmen juga berencana mengundang kembali 70 lembaga mitra kerja sama tahap 2 untuk menyusun tindak lanjut bimbingan teknis berbagai program prioritas Kemendikdasmen.</p>
                    <p>Ditjen PAUD Dasmen senantiasa terbuka atas partisipasi seluruh pemangku kepentingan dan mitra pendidikan untuk bersama-sama mewujudkan Pendidikan Bermutu untuk Semua.</p>
