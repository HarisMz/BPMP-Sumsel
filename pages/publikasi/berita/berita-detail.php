                    <p>Jakarta, Kemendikdasmen --- Kementerian Pendidikan Dasar dan Menengah (Kemendikdasmen) dan Pimpinan Pusat Aisyiyah berkomitmen untuk memperkuat pendidikan karakter di Indonesia. Sejumlah langkah strategis dilakukan untuk membangun generasi yang berkarakter kuat, berintegritas, serta berdaya saing global. Program-program prioritas dalam pembangunan pendidikan nasional, khususnya yang berkaitan dengan karakter dan inklusivitas, terus diperkenalkan untuk menghadapi tantangan zaman yang semakin kompleks.</p>
                    <p>Dalam kesempatan paparan pertama, Kepala Pusat Penguatan Karakter (Kapuspeka), Rusprita Putri Utami, memaparkan tentang peran penting pendidikan karakter dalam mewujudkan visi pemerintahan yang lebih baik. Di dalam arahan yang diberikan, ia menyampaikan bahwa program-program prioritas dari Kabinet Merah Putih sangat berkaitan dengan isu penguatan karakter.</p>
                    <p>"Ada delapan program prioritas nasional, dan empat di antaranya sangat berkaitan erat dengan isu karakter. Ini terlihat jelas dalam upaya memperkokoh ideologi Pancasila, memperkuat pemberdayaan sumber daya manusia, serta menciptakan kebijakan yang inklusif dan berbasis gender," ujarnya.</p>
                    <p>Pentingnya integrasi nilai-nilai Pancasila dalam kehidupan sehari-hari, terutama di kalangan generasi muda, juga menjadi sorotan. Menurutnya, karakter bangsa harus terwujud dalam pendidikan yang mengedepankan nilai-nilai religius, moral, disiplin, kreatif, serta kerja keras. Tidak hanya itu, generasi muda juga diharapkan dapat mengimplementasikan nilai-nilai tersebut dalam kehidupan sehari-hari, serta memiliki kualifikasi global.</p>
                    <p>Salah satu langkah yang dilakukan untuk mewujudkan pendidikan berkarakter ini adalah melalui program pelatihan bimbingan konseling untuk guru, peningkatan kompetensi guru BK dan guru agama, serta penanaman karakter melalui 7 Kebiasaan Anak Indonesia. Program ini bertujuan untuk mencegah perundungan dan kekerasan seksual yang marak terjadi di sekolah. Berdasarkan hasil PISA 2022, sebanyak 25% anak perempuan dan 30% anak laki-laki melaporkan menjadi korban perundungan beberapa kali dalam sebulan.</p>
                    <p>Sementara itu, data dari Komisi Perlindungan Anak Indonesia (KPAI) mencatatkan 2.133 kasus keluhan perlindungan anak pada tahun 2024, dengan kejahatan seksual dan kekerasan fisik/psikologis menjadi masalah yang paling dominan.</p>
                    <p>Pemerintah juga menekankan pentingnya lingkungan belajar yang aman, nyaman, dan menggembirakan, yang salah satunya dapat dicapai melalui pendidikan inklusif. Pendidikan inklusif berfokus pada penyediaan akses pendidikan bagi semua anak, termasuk mereka yang mengalami disabilitas, anak-anak rentan, serta mereka yang menjadi korban kekerasan.</p>
                    <p>Paparan kedua yang disampaikan oleh Tim Ahli Mendikdasmen, Rita Pranawati mengangkat tema "Membangun Zona Aman Belajar" dengan fokus pada menciptakan lingkungan belajar yang inklusif dan berkarakter. Rita mengingatkan bahwa kebiasaan baik dan karakter positif harus diajarkan sejak dini. Dalam konteks ini, pendidikan karakter bukan hanya tugas sekolah, tetapi juga peran orang tua dan masyarakat.</p>
                    <p>"Kebiasaan baik, seperti tidur tepat waktu, bangun pagi, dan berolahraga, harus dibiasakan. Ini adalah bagian dari pendidikan karakter yang tidak bisa ditunda," ujarnya. Menurutnya, perkembangan teknologi dan media sosial juga memengaruhi karakter anak-anak, di mana banyak dari mereka yang menghabiskan waktu lebih banyak dengan ponsel daripada berinteraksi secara sosial.</p>
                    <p>Pendidikan inklusif adalah pendidikan yang memberikan kesempatan yang sama bagi setiap anak, terlepas dari latar belakang, kondisi fisik, maupun kemampuan intelektual mereka. Di dalamnya, semua anak memiliki hak yang sama untuk mendapatkan pendidikan yang layak, termasuk anak-anak yang memiliki kebutuhan khusus, seperti disabilitas atau anak-anak korban kekerasan.</p>
                    <p>"Pendidikan inklusif memberikan ruang untuk keberagaman, mengajarkan nilai-nilai seperti penghargaan terhadap perbedaan dan kesetaraan. Ini sangat penting untuk memastikan bahwa setiap anak dapat berkembang dengan baik, tanpa terkecuali," tambahnya.</p>
                    <p>Pentingnya kerja sama antara guru dan orang tua dalam menciptakan pendidikan karakter yang efektif juga menjadi sorotan. Guru harus menjadi teladan dan memberikan bimbingan yang tidak hanya bersifat akademik, tetapi juga karakter yang mencakup sikap disiplin, tanggung jawab, serta kerja sama yang baik dengan sesama.</p>
                    <p>Paparan ketiga yang disampaikan oleh Dosen FIP Universitas Muhammadiyah Jakarta, Susilahati, menekankan pentingnya integrasi nilai-nilai karakter dalam kurikulum pendidikan. Susilahati menjelaskan bahwa pendidikan karakter harus diajarkan dalam semua mata pelajaran, mulai dari pendidikan agama, bahasa Indonesia, hingga ilmu pengetahuan alam (IPA).</p>
                    <p>"Karakter mencakup sikap seperti keinginan untuk melakukan yang terbaik, berpikir kritis, dan bertanggung jawab. Ini harus diintegrasikan dalam setiap mata pelajaran yang diajarkan di sekolah," jelasnya.</p>
                    <p>Menurutnya, dalam Kurikulum Merdeka, nilai-nilai seperti religius, jujur, disiplin, kerja keras, kreatif, mandiri, serta gotong-royong harus menjadi bagian integral dari proses belajar-mengajar. Karakter ini tidak hanya harus diajarkan dalam konteks teori, tetapi juga dalam penerapannya sehari-hari, seperti dalam pelajaran matematika, IPA, olahraga, dan lainnya.</p>
                    <p>"Setiap mata pelajaran harus mengajarkan nilai-nilai karakter. Misalnya, dalam pelajaran matematika, kita bisa mengajarkan ketepatan, kesabaran, dan kerja sama. Sedangkan dalam pelajaran olahraga, kita bisa mengajarkan semangat sportivitas, disiplin, serta kerja sama dalam tim," tambahnya.</p>
                    <p>Peserta seminar dari berbagai kalangan, seperti Erna, seorang guru di TK Aisyiyah 20 Tebet Barat, Jakarta Selatan, menyatakan pentingnya pembelajaran karakter yang mendalam. "Kami banyak mendapatkan manfaat dari seminar ini, terutama dalam memahami bagaimana karakter anak, yang setiap anak itu berbeda. Kami belajar bagaimana cara menyikapi anak yang mungkin sedang tidak mood dan bagaimana memberikan pendekatan yang penuh kasih sayang," ujarnya.</p>
                    <p>Yuni Susanti, Kepala Sekolah di TK Aisyiyah 84 Cengkareng, juga menekankan pentingnya pendidikan karakter di usia dini. "Kami sebagai sekolah penggerak selalu menekankan pentingnya pembiasaan dan penerapan disiplin positif untuk membentuk karakter anak sejak dini. Pembiasaan ini sangat penting agar anak dapat tumbuh menjadi individu yang bertanggung jawab dan mandiri," ungkapnya.</p>
                    <p>Ayu Nintias, anggota Komite Sekolah, menambahkan, "Kerja sama antara guru, kepala sekolah, dan komite sangat penting untuk mendukung pembentukan karakter anak. Kami sangat mendukung sekolah inklusif karena ini memberikan kesempatan bagi semua anak, termasuk mereka yang berkebutuhan khusus, untuk mendapatkan pendidikan yang layak."</p>
                    <p>Pendidikan karakter yang inklusif dan berbasis nilai moral yang kuat menjadi pondasi penting bagi kemajuan bangsa. Melalui berbagai program dan kebijakan yang mengedepankan integritas, disiplin, serta penguatan karakter, pemerintah Indonesia berkomitmen untuk menciptakan generasi yang tidak hanya cerdas, tetapi juga memiliki karakter yang kuat dan mampu beradaptasi dengan tantangan global. Keterlibatan semua pihak, mulai dari sekolah, orang tua, hingga masyarakat, sangat diperlukan untuk mewujudkan tujuan ini. .*** (Penulis: Duma Sabhatani/Editor: Denty A.)</p>
